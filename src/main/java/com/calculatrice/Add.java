package com.calculatrice;

/**
 * Opération d'addition de la calculatrice.
 */
public class Add {

    /**
     * Retourne la somme de a et b.
     *
     * @param a premier opérande
     * @param b second opérande
     * @return a + b
     */
    public int add(int a, int b) {
        return a + b;
    }
}
